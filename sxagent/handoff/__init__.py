"""**交接 · 共享词汇表** —— 段名 / 来源标注 / 状态词汇 / 出口分类 / 排版 / 跳声明。

    sxagent/handoff/
      __init__.py    ← 本文件：**共享词汇表**（所有交接点共用这一份）
      briefing.py    ← 委托单（平台 → 执行器）：Task/Turn/QA schema ＋ render_briefing
      receipt.py     ← 回执（执行器 → 主 agent）：Receipt schema ＋ render_receipt
      ask.py · nudge.py · ledger.py · decision.py  ← 另外四跳（schema ＋ 模板同址）

## 这个文件是什么

全库**唯一的词汇来源**：交接单上每一段叫什么、来源怎么标、状态怎么命名、出口怎么分类、
每一跳渲染哪几段 —— 都只在这里定义一次。**渲染器从这里取，记录层也从这里取** ——
"两边各抄一份、然后悄悄失配"因此**结构上不可能**。

## 设计原则（不变量）

1. **一个语义一处定义**。段名 / 来源标注 / 状态名 / 出口分类 / 排版 / 跳声明都只在这一份里；
   加一个段就登记进 `SECTION` ＋ `HOPS`，**别处不许就地写字符串**。
2. **不许反解析**：结构一旦渲染成文本就**回不去** —— 段名 / 来源标注 / 自由文本混在一行，
   自由文本里可以出现任何东西，任何措辞变更对解析器**不可见**。
   正解：**先有对象，注入那一刻才渲染**；对象搭同一趟车
   （`ToolMessage.additional_kwargs` —— 实测**不会漏给模型**）。没有对象就**如实显示成一段话**。
3. **来源标注属于结构**，不是措辞装饰：记录层切段时要**原样剥掉**它（靠 `SOURCE_NOTE`
   这张表，不靠"行首是 `（…）` 就剥"那种启发式 —— 它会误剥 `（无）` 这种**真内容**）。
4. **用词是一个体系** —— 同一个语义一个词，见下面「关键取舍 ③」。
5. **排版一条规矩**：段名 0 列 → 来源 2 列 → 段体 2 列，每下一层 +2（`BODY`）。

## 关键取舍

**① 来源那一行只回答一件事：这段段体是谁的话。**

- **是别人的话** → 必须标：`**主 agent 交代的**` / `**用户说的**` / `**它说的**` / `**它申报的**`
- **是平台自己写的框架话** → **不标**（自证没意义）—— 【下一步】【续跑提示】【平台要求】
  【请判断】【平台提示】【平台故障】都不标
- **混来源的段**（【问答经过】）→ 段级**填不了**来源，那一行只说"**逐条标了来源**"，
  真正的来源标在**每一项**上

**② 称呼：段体可以用「你」，来源标注一律第三人称。**
段体是平台**在对读的人说话**（试答整张都是这么写的）；来源标注是**元信息**
（"这段是谁的话"）—— **不随读的人变**（主 agent / 执行器 / 用户）。
⇒ "同一个段出现在两个跳里、称呼打架"就**结构上不可能**（`SOURCE_NOTE` 按段名索引，只有一份）。

**③ 同一个语义一个词。**

| 定哪个 | 不许再用 |
|---|---|
| **委派**（派活这个动作） | ~~派发~~ · ~~派出去~~ · ~~派给~~ · ~~派了~~ · ~~重派~~ |
| **产物**（名词）／**产出**（**只做动词**） | ~~成品~~；不许拿"产出"当名词（"产出有多长" ✗） |
| **梗概** | ~~摘要~~ · ~~一句话~~ |
| **要信息**（状态）／**申报**（动作） | ~~请求信息~~ · ~~等答复~~ · ~~提问~~ |

⚠️ 这些"不许再用"的词出现在**运行期可见的字符串**里，必须能被检查发现。

**④ 组织方式：一个交接点 = 一个模块 = schema ＋ 模板** —— 改一处就够（高内聚低耦合）。
"""


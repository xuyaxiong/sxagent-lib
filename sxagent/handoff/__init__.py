# ──────────────────────────── 排版 ────────────────────────────

#: **段体缩进** —— 段名在 0 列，段体一律在 2 列，每下一层再 +2。
#:
#: 一条规矩治三种破法：① 多行的「答」续行掉到 0 列、整块脱出所在段落；
#: ② 「答」和「问」的续行同缩进 → 答看起来像问的一部分；③ 被点名那几轮的原文在 0 列、
#: 跟它上面那个 `-` 对不齐。
#:
#: ⚠️ 定义放这里、不放各跳自己家里：*"任何涉及交接的地方你都不要搞两套
#: —— 你显示给我看的，就是传给 llm 看的"*。排版是**所有交接点共用的一条规矩**。
BODY = "  "


def section_head(key: str) -> list[str]:
    """**段名独占一行** ＋（有来源的话）**来源另起一行** —— 两个交接点共用这一条。

    现在：**段名 0 列 → 来源 2 列 → 段体 2 列**（段体由调用方接，见 `body_lines`）。
    改之前段名后面直接跟一长串括号说明、段体只缩 2 格 —— 两行看着像同一个层级，
    标题不像标题（用户："仿佛是同一个层级"）。
    """
    out = [SECTION[key]]
    note = SOURCE_NOTE.get(key)
    if note:
        out.append(f"{BODY}{SOURCE_LABEL}{note}")
    return out


def body_lines(text: object, pad: str = BODY) -> list[str]:
    """一个**多行值**整块缩进 —— 每一行都缩。

    ⚠️ **空行也留缩进**（留成 `pad`）：留成空串的话，块被空行切断 ——
    上面那行是列表项时，markdown 里后面几行就散到块外面去了。
    """
    raw = str(text or "")
    if not raw.strip():
        return []
    return [f"{pad}{ln}" if ln.strip() else pad for ln in raw.splitlines()]


def bullet_lines(text: object, pad: str = BODY) -> list[str]:
    """一个**可能多行**的列表项 —— 首行带 `- `，续行对齐到**文字**，不顶回 0 列。"""
    ls = str(text or "").splitlines() or [""]
    return [f"{pad}- {ls[0]}", *(f"{pad}  {ln}" for ln in ls[1:])]



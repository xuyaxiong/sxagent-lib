"""推回去（平台 → 执行器）：这一轮既没交东西也没申报要信息时，喂回去让它接着干。

一段模板，经 `render_hop("nudge", …)` 渲染成【平台要求】。

## 不变量

1. 只说平台看得见的两件事实：没交产物（这一轮没调 `write_artifact`），没申报要信息（没调
   `ask_user`）。平台不读正文，没有别的可说。
2. 点明两条出路：交付，或者用 `ask_user` 说清缺什么。把正确的路摆在它面前，不猜它想说什么。
3. 渲染走唯一那条渲染路（`render_hop`）。"""

from __future__ import annotations

from sxagent.handoff import render_hop


def nudge_text() -> str:
    """推它继续时说什么 —— 只说平台看得见的两件事实 ＋ 两条出路。"""
    return render_hop(
        "nudge",
        {
            "nudge": "\n".join(
                [
                    "这一轮**既没有交付产物，也没有说明你需要什么信息**。",
                    "",
                    "两条路，选一条走：",
                    "",
                    "- **干完了** → 用 `write_artifact` 把成果**交付成产物**"
                    "（正文写在回复里平台看不到，不算交付）；",
                    "- **缺信息、干不下去** → 用 `ask_user` **说清缺什么**"
                    "（平台会先问主 agent，它答不上再转用户）。",
                    "",
                    "不要用「已完成」这类话收尾 —— 那句话不构成交付。",
                ]
            )
        },
    )
